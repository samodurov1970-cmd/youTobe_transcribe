типа заявок-ордеров

1. **Лимитный покупатель** — хочет купить, но только по своей цене или ниже. Стоит в стакане, ждёт.  
    
2. **Рыночный покупатель** — хочет купить прямо сейчас по любой текущей цене. Забирает лучшие предложения из стакана.
    
3. **Лимитный продавец** — хочет продать, но только по своей цене или выше. Стоит в стакане, ждёт.
    
4. **Рыночный продавец** — хочет продать прямо сейчас по любой текущей цене. Бьёт по лучшим заявкам на покупку.
    

## 4 участника рынка (в этой логике)

1. **Лимитный покупатель** — пассивный участник, создаёт ликвидность, торгует от уровня.
    
2. **Рыночный покупатель** — агрессивный участник, забирает ликвидность, ему нужна скорость.
    
3. **Лимитный продавец** — пассивный участник, создаёт ликвидность, продаёт от уровня.
    
4. **Рыночный продавец** — агрессивный участник, забирает ликвидность, ему нужен выход сейчас.
    

## Как они взаимодействуют

|Кто|С кем|Результат|
|---|---|---|
|Рыночный покупатель|Лимитный продавец|Сделка по цене продавца|
|Рыночный продавец|Лимитный покупатель|Сделка по цене покупателя|
|Лимитный покупатель|Лимитный продавец|Сделка, когда цены пересекаются|
|Рыночный покупатель|Рыночный продавец|Невозможно напрямую — нужен стакан|

**Суть:** лимитные заявки формируют **стакан**, рыночные заявки его **двигают**. Рыночные покупатели двигают цену вверх, рыночные продавцы — вниз. Лимитные — тормозят движение.

# Структура рынка

Разберём послойно — от физической инфраструктуры до логики движения цены.

---

## 1. Уровни структуры (сверху вниз)

|Уровень|Что это|Пример|
|---|---|---|
|**Регулятор**|Законы, лицензии, надзор|ЦБ РФ, SEC, FCA|
|**Биржа**|Площадка, правила торгов, стакан|MOEX, NYSE, Binance|
|**Клиринг**|Гарант сделок, расчёты|НКЦ, DTCC|
|**Брокер**|Доступ для участников|Тинькофф, IB|
|**Участники**|Те, кто торгует|Фонды, трейдеры, маркет-мейкеры|
|**Инструменты**|Что торгуется|Акции, фьючерсы, облигации|

---

## 2. Структура участников (по роли)

text

┌─────────────────────────────────────────┐
│           РЕГУЛЯТОР + БИРЖА             │
│         (правила, надзор)               │
└─────────────────────────────────────────┘
                  ↓
┌─────────────────────────────────────────┐
│         МАРКЕТ-МЕЙКЕРЫ                  │
│   (ликвидность, спред, стакан)          │
└─────────────────────────────────────────┘
                  ↓
┌─────────────────────────────────────────┐
│      ИНСТИТУЦИОНАЛЫ                     │
│  (банки, фонды, алгоритмы — объём)      │
└─────────────────────────────────────────┘
                  ↓
┌─────────────────────────────────────────┐
│      РОЗНИЦА                            │
│   (частные трейдеры — масса)            │
└─────────────────────────────────────────┘

---

## 3. Структура стакана (микроструктура)

Это **ядро рынка** — здесь встречаются заявки.

text

        СТАКАН (Order Book)
┌──────────────────────────────────┐
│  ПРОДАВЦЫ (Ask)                  │
│  101.5 ₽ — 200 шт  ← лимитные    │
│  101.0 ₽ — 500 шт                │
│  100.5 ₽ — 300 шт                │
├──────────────────────────────────┤
│  СПРЕД (разница)                 │
│  ← здесь встречаются заявки      │
├──────────────────────────────────┤
│  ПОКУПАТЕЛИ (Bid)                │
│  100.0 ₽ — 400 шт  ← лимитные    │
│   99.5 ₽ — 600 шт                │
│   99.0 ₽ — 250 шт                │
└──────────────────────────────────┘

**Что происходит:**

- **Рыночный покупатель** бьёт по Ask → цена растёт
    
- **Рыночный продавец** бьёт по Bid → цена падает
    
- **Лимитные** стоят и ждут → создают ликвидность
    

---

## 4. Структура движения цены

|Фаза|Что происходит|Кто действует|
|---|---|---|
|**Накопление**|Цена в боковике, лимитники набирают|Лимитные покупатели|
|**Тренд вверх**|Рыночные покупатели выбивают Ask|Рыночные покупатели|
|**Распределение**|Цена тормозит, лимитники продают|Лимитные продавцы|
|**Тренд вниз**|Рыночные продавцы выбивают Bid|Рыночные продавцы|

---

## 5. Структура ликвидности

text

ЛИКВИДНОСТЬ = способность купить/продать без движения цены
┌────────────────────────────────┐
│  ВЫСОКАЯ                       │
│  • много заявок в стакане      │
│  • узкий спред                 │
│  • маркет-мейкеры активны      │
│  Пример: AAPL, SBER            │
├────────────────────────────────┤
│  НИЗКАЯ                        │
│  • мало заявок                 │
│  • широкий спред               │
│  • проскальзывание             │
│  Пример: мелкие акции, альты   │
└────────────────────────────────┘

---

## 6. Структура потоков (кто кому платит)

text

Розница → Брокеру (комиссия)
Брокер → Бирже (комиссия)
Биржа → Клирингу (расчёты)
Все → Регулятору (надзор)
Маркет-мейкер → зарабатывает на СПРЕДЕ
Институционал → зарабатывает на ТРЕНДЕ
Розница → чаще платит ВСЕМ

---

## 7. Иерархия влияния на цену

text

1. Маркет-мейкеры     — формируют стакан
2. Институционалы     — двигают объёмом
3. Алгоритмы          — ускоряют движение
4. Розница            — создаёт массу, но не направление

