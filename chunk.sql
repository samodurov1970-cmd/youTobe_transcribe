## 2. Что такое структура рынка

**Структура рынка** — это **общее направление цены в сторону наименьшего сопротивления**. Она состоит из **последовательности максимумов и минимумов**, что позволяет определить тренд и возможное движение цены в дальнейшем.

**Рынок всегда движется в одном из трёх направлений.**

### Восходящий тренд

**Когда видим, что цена формирует более высокие максимумы и более высокие минимумы** (higher high + higher low), то можем рассматривать такое ценообразование как **восходящий тренд**.

**На этой схеме** — пример, который вы скорее всего уже видели десятки раз в книгах, обучениях и т.д. Это **идеальный тренд**, который не очень похож на то, что происходит на реальном графике. Здесь видите, что максимумы и минимумы становятся **всё выше и выше**, и такой тренд сможет торговать любой желающий, и ему будет сложно ошибиться, потому что здесь всё очевидно.

**Мы ждём**, что после нового максимума будет **коррекция**, которая образует **higher low** (более высокий минимум). И на нём мы откроем позицию с целью формирования **нового higher high** (более высокого максимума). По сути это так и работает, и будет работать в дальнейшем.

**Только правильно идентифицировать структуру** получается не у всех, потому что на реальном графике чаще всего будете видеть структуру, схожую со **второй схемой**.

### Реальный тренд

**Цена импульсно двигается выше** и начинает **медленно корректироваться** в рамках формирования **higher low**. На данном этапе **новички уже путаются** и думают, что начался **нисходящий тренд**. Это ошибка — он пока что **локальный**.

**А смена структуры** будет только тогда, когда произойдёт **обновление higher low**, откуда сформировался **higher high**. В данном случае обновление этого минимума будет считаться **сломанной структурой**.

**После образования нового higher low** цена двигается выше, и **локально зарождается такая же восходящая структура**. Этот higher low будет считаться **подтверждённым** только после того, как цена обновит **предыдущий higher high**. И теперь если цена пробьёт **подтверждённый higher low**, то **бычья структура будет сломана**. На графике образуется **lower low**, и скорее всего рынок **сменит своё направление**.

**В следующих видео** более подробно поговорим про то, как работать со структурой **внутри структуры**, а в этом видео будут **базовые вещи**, которые нужно обязательно знать, даже если вы торгуете уже достаточно долго. Всё равно посмотрите серию видео про структуру и убедитесь, что вы правильно её используете.

