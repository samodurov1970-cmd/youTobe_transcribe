## 3. Как определять свингхаи и свинглои

**Для определения структурных элементов** находите **свингхаи и свинглои**. Зачастую у многих с этим **большая проблема**.

**Часто вижу**, что трейдеры видят **большую тень свечи** или просто **большую свечу** и считают её за структурный элемент. Впоследствии из-за этой ошибки их анализ оказывается **неправильным**. Так что сейчас быстро разберём этот момент.

### Свингхай

**Свингхай формируется тремя свечами.** Две свечи **слева и справа** и одна **верхняя свеча посередине**.

### Свинглоу

**Свинглоу образуется абсолютно таким же образом**, только в обратную сторону. Также **две свечи по бокам** и одна **нижняя свеча по середине**.

### Более значимые свинги

**В большинстве случаев явные и более значимые свинги формируются пятью свечами.** Логика такая же, но по бокам будет уже **по две свечи**.

**Схематически** это будет выглядеть таким образом: верхняя свеча по середине и ниже две свечи левее и две правее неё. Такая же логика для формирования свингхая.

### Пример на реальном графике

**Рассмотрим на текущем боковике, как определять свингхаи и лои на реальном графике.** Это **дневной таймфрейм**, но информация из видео автора работает **на всех таймфреймах**, вплоть до секундных графиков, потому что **рынок фрактален**.

**Если будете определять структуру на 15-минутном таймфрейме**, вам нужно будет сделать то же самое.

**Здесь видим свингхай**, потому что по левую сторону в верхней свечи есть **две свечи**, и по правую сторону также **ещё две свечи**.

**Ниже образовался свинглоу** — есть нижняя свеча и ещё **две по бокам**.

**Дальше от него сформировался ещё один свингхай** — одна свеча по середине и по **две слева и справа**.

**Цена падает ниже** и формируется **свинглоу** — одна свеча слева и справа.

**Надеюсь, что уже на этом этапе всё стало понятно.** Когда автор анализирует графики, он **не считает, сколько там свечей по бокам** — это и так визуально видно: здесь сформировался свингхай, здесь свинглоу, дальше такая же логика: хай, лоу, хай, лоу и так далее.

**Если что, цвет свечи не имеет никакого значения.** Свингхай может быть образован **чёрной свечей**, а свинглоу — **зелёной**. Если у вас возникают с этим трудности, то спустя некоторое время практики вы сможете определять свинги на **любом графике**. Это очень легко. Ну и соответственно сможете корректно работать по структуре.

