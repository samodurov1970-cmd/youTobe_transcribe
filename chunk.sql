## 4. Нисходящий тренд

**Возвращаемся к тренду.** Помимо восходящего движения, цена может двигаться **вниз** — это будет **нисходящий тренд**.

**Когда видим, что цена формирует более низкие минимумы и более низкие максимумы** (lower low + lower high), то можем рассматривать такое ценообразование как **нисходящий тренд**.

**Здесь происходит абсолютно всё то же самое**, что и на восходящем тренде, только в другую сторону. Поэтому к нижнему примеру вы можете понять, как такая структура должна выглядеть.

**Здесь ваша задача** — определить **общее направление цены** и стараться торговать в соответствии с ним. На формировании **lower high** будете стараться открыть позицию с целью **обновления lower low**. На это нужны **факторы и чёткий сетап**, одной структуры будет недостаточно, но следующие видео прояснят этот момент.

### Реальный нисходящий тренд

**Обращаем внимание на график, приближенный к реальному.** Цена импульсно формирует **lower low** и коррекционно **lower high**. Здесь зарождается **локальная восходящая структура**, но после этого цена двигается **ещё ниже** и обновляет **предыдущий lower low**. Тем самым **подтверждает этот lower high**.

**Потом видите коррекцию**, которая обновляет этот **локальный хай**. Многие подумают, что уже здесь был **слом структуры**, но это **не так**. В рамках текущей структуры нисходящий тренд будет **сломан**, когда цена пробьёт **подтверждённый lower high**. Здесь будет **слом структуры**.

### Смена тренда

**Смотрим на последний lower low.** Если цена начнёт двигаться в восходящем направлении, будет обновлён **lower high**, который сформировал lower low. Тогда у нас сформируется **higher high**, потом **higher low** и ещё один **higher high**.

**Сейчас расставлю лейблинг.** Здесь будет **higher high**, потому что мы обновили **структурный lower high**. Потом это нисходящее движение будет считаться **higher low**, то есть более высокий минимум, потому что **не было обновления предыдущего лоя**. А это движение сформировало **higher high** и **подтвердило восходящий тренд**.

**В общем**, так будет выглядеть **смена тренда схематически**.

